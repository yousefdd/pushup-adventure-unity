"""Generates the Unity project's content from the Flutter project's sources,
so names, numbers and Arabic text never drift between the two games.

    python3 tools/port_from_flutter.py /path/to/repraid

Writes Assets/Scripts/Core/Generated/WorldData.cs and LocAr.cs.
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else '/home/user/repraid'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'Assets', 'Scripts', 'Core', 'Generated')


def dart_strings(text):
    """Every single-quoted Dart string literal, with adjacent literals joined,
    as (start, end, value)."""
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if text.startswith('//', i):
            i = text.index('\n', i) if '\n' in text[i:] else len(text)
            continue
        if c == "'":
            j, buf = i + 1, []
            while text[j] != "'":
                if text[j] == '\\':
                    nxt = text[j + 1]
                    buf.append({'n': '\n', 't': '\t', '$': '$', "'": "'", '\\': '\\'}.get(nxt, nxt))
                    j += 2
                    continue
                buf.append(text[j])
                j += 1
            val = ''.join(buf)
            # adjacent literal concatenation: 'a' 'b'
            if out and text[out[-1][1]:i].strip() == '':
                s, _, v = out.pop()
                out.append((s, j + 1, v + val))
            else:
                out.append((i, j + 1, val))
            i = j + 1
            continue
        i += 1
    return out


def dart_map(path):
    text = open(path, encoding='utf-8').read()
    lits = dart_strings(text)
    pairs = {}
    for (s1, e1, k), (s2, e2, v) in zip(lits, lits[1:]):
        if text[e1:s2].strip() == ':':
            pairs[k] = v
    return pairs


def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


# ---------------------------------------------------------------- Arabic
ar = {}
ar.update(dart_map(os.path.join(SRC, 'lib/i18n/ar.dart')))
ar.update(dart_map(os.path.join(SRC, 'lib/i18n/world_ar.dart')))
with open(os.path.join(OUT, 'LocAr.cs'), 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tools/port_from_flutter.py from the Flutter project. Do not edit.\n')
    f.write('using System.Collections.Generic;\n\nnamespace DiceQuest.Core\n{\n')
    f.write('    public static partial class Loc\n    {\n')
    f.write('        static readonly Dictionary<string, string> Ar = new Dictionary<string, string>\n        {\n')
    for k, v in ar.items():
        f.write(f'            {{ {cs(k)}, {cs(v)} }},\n')
    f.write('        };\n    }\n}\n')

# ---------------------------------------------------------------- worlds
wd = open(os.path.join(SRC, 'lib/modes/rpg/world_data.dart'), encoding='utf-8').read()
blocks = wd.split('ChapterDef(')[1:]
chapters = []
for b in blocks:
    def field(name, kind='str'):
        m = re.search(name + r":\s*('(?:[^'\\]|\\.)*'|[0-9A-Fa-fx.]+)", b)
        if not m:
            raise SystemExit('missing ' + name)
        v = m.group(1)
        return dart_strings(v)[0][2] if v.startswith("'") else v
    foes = []
    for m in re.finditer(r"FoeKind\(([\s\S]*?)\)(?=,|\s*\])", b):
        args = m.group(1)
        lits = [x[2] for x in dart_strings(args)]
        num = re.search(r"'\s*,\s*([0-9.]+)\s*,", args).group(1)
        ab = re.search(r"FoeAbility\.(\w+)", args).group(1)
        front = bool(re.search(r"FoeAbility\.\w+\s*,\s*true", args))
        foes.append((lits[0], lits[1], num, lits[2], ab, front))
    chapters.append(dict(number=field('number'), id=field('id'), roman=field('roman'), name=field('name'),
                         blurb=field('blurb'), start=field('startLevel'), ground=field('ground'), foes=foes))

with open(os.path.join(OUT, 'WorldData.cs'), 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tools/port_from_flutter.py from the Flutter project. Do not edit.\n')
    f.write('namespace DiceQuest.Core\n{\n    public static class WorldData\n    {\n')
    f.write('        public static readonly ChapterDef[] Chapters =\n        {\n')
    for c in chapters:
        f.write(f'            new ChapterDef({c["number"]}, {cs(c["id"])}, {cs(c["roman"])}, {cs(c["name"])}, {cs(c["blurb"])}, '
                f'{c["start"]}, 0x{c["ground"][4:] if c["ground"].startswith("0xFF") else c["ground"][2:]},\n')
        f.write('                new[]\n                {\n')
        for (name, img, m, quote, ab, front) in c['foes'][:5]:
            f.write(f'                    new FoeKind({cs(name)}, {cs(img)}, {m}f, {cs(quote)}, FoeAbility.{ab[0].upper() + ab[1:]}, {str(front).lower()}),\n')
        name, img, m, quote, ab, front = c['foes'][5]
        f.write('                },\n')
        f.write(f'                new FoeKind({cs(name)}, {cs(img)}, {m}f, {cs(quote)}, FoeAbility.{ab[0].upper() + ab[1:]}, {str(front).lower()})),\n')
    f.write('        };\n    }\n}\n')
print('chapters', len(chapters), 'foes', sum(len(c['foes']) for c in chapters), 'arabic strings', len(ar))
